/**
 * รหัสเอกสารที่ต้องไม่ชนกันข้ามอาคาร
 *
 * ทุกอาคารเก็บรวมใน collection เดียวกัน รหัสที่ประกอบจากเลขห้องอย่างเดียว
 * จะชนกันทันทีที่อาคารที่สองมีห้อง 101 เหมือนกัน แล้วเขียนทับของอาคารแรกเงียบๆ
 */

/** อาคารแรกที่ย้ายมาจาก V2 — รหัสเดิมของมันไม่มีชื่ออาคารนำหน้า */
const LEGACY_PROPERTY_ID = "wlp1";

/**
 * การจดมิเตอร์ของห้องหนึ่งในรอบหนึ่ง — ห้องเดียวรอบเดียวมีได้ใบเดียว ออกบิลซ้ำก็เขียนทับใบเดิม
 *
 * วิไลเพลส 1 ใช้ MR-202610-402 มาตั้งแต่ V2 ต้องคงรูปเดิมไว้
 * ไม่งั้นออกบิลรอบเดิมซ้ำจะได้การจดสองใบในรอบเดียว แล้วไม่รู้ว่าเลขครั้งก่อนคือใบไหน
 */
export function meterReadingId(propertyId: string, cycle: string, roomNo: string): string {
  return propertyId === LEGACY_PROPERTY_ID ? `MR-${cycle}-${roomNo}` : `MR-${propertyId}-${cycle}-${roomNo}`;
}
